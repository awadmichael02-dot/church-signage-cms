-- Starter schema. Review and test Row Level Security before using.
create table if not exists public.screens (
  id text primary key,
  name text not null,
  ticker text not null default '',
  updated_at timestamptz not null default now()
);

create table if not exists public.slides (
  id bigint generated by default as identity primary key,
  screen_id text not null references public.screens(id) on delete cascade,
  image_url text not null,
  title text not null default '',
  duration_seconds integer not null default 15 check (duration_seconds between 5 and 600),
  sort_order integer not null default 0,
  starts_at timestamptz,
  ends_at timestamptz,
  enabled boolean not null default true,
  created_at timestamptz not null default now()
);

insert into public.screens(id, name) values
  ('lobby', 'Lobby'),
  ('sanctuary', 'Sanctuary')
on conflict (id) do nothing;

alter table public.screens enable row level security;
alter table public.slides enable row level security;

-- Public read policies allow the Roku players to fetch display content.
-- For production, consider a separate read-only view/API and limit exposed fields.
create policy "Public can read screens" on public.screens
for select to anon, authenticated using (true);

create policy "Public can read enabled slides" on public.slides
for select to anon, authenticated using (enabled = true);

